/* 4. Creación de las tablas según el diseño físico */
/* Tabla CATEGORIA */
CREATE TABLE CATEGORIA (
    IDCAT INT GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMCAT VARCHAR2(60),
    CONSTRAINT CAT_PK PRIMARY KEY (IDCAT)
);

/* Tabla PERSONA */
CREATE TABLE PERSONA (
    IDPER INT GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DNIPER CHAR(8),
    NOMPER VARCHAR2(60),
    APEPER VARCHAR2(80),
    EMAPER VARCHAR2(80),
    CELPER CHAR(9),
    TIPPER CHAR(1),
    ESTPER CHAR(1) DEFAULT 'A',
    CONSTRAINT PER_PK PRIMARY KEY (IDPER)
);

/* Tabla PRODUCTO */
CREATE TABLE PRODUCTO (
    CODPROD CHAR(3),
    NOMPRO VARCHAR2(50),
    IDCAT INT,
    PREPRO NUMBER(8,2),
    STOCKPRO INT,
    ESTPRO CHAR(1) DEFAULT 'A',
    CONSTRAINT PROD_PK PRIMARY KEY (CODPROD),
    CONSTRAINT PROD_CAT_FK FOREIGN KEY (IDCAT)
    REFERENCES CATEGORIA(IDCAT)
);

/* Tabla VENTA */
CREATE TABLE VENTA (
    IDVEN INT GENERATED BY DEFAULT ON NULL AS IDENTITY,
    FECVEN DATE,
    IDCLI INT,
    IDVEND INT,
    TIPPAGVEN CHAR(1),
    ESTVEN CHAR(1),
    CONSTRAINT VEN_PK PRIMARY KEY (IDVEN),
    CONSTRAINT VEN_CLI_FK FOREIGN KEY (IDCLI)
    REFERENCES PERSONA(IDPER),
    CONSTRAINT VEN_VEND_FK FOREIGN KEY (IDVEND)
    REFERENCES PERSONA(IDPER)
);

/* Tabla VENTA_DETALLE */
CREATE TABLE VENTA_DETALLE (
    IDVENDET INT GENERATED BY DEFAULT ON NULL AS IDENTITY,
    IDVEN INT,
    CODPROD CHAR(3),
    CANVENDET INT,
    CONSTRAINT VENDET_PK PRIMARY KEY (IDVENDET),
    CONSTRAINT VENDET_VEN_FK FOREIGN KEY (IDVEN)
    REFERENCES VENTA(IDVEN),
    CONSTRAINT VENDET_PROD_FK FOREIGN KEY (CODPROD)
    REFERENCES PRODUCTO(CODPROD)
);
